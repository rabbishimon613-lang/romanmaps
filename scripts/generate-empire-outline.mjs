#!/usr/bin/env node
/**
 * Generates a heavily simplified coastline silhouette for the `LocatorThumbnail` component
 * [13-P0-3] — a "you are here" locator map shown in place of a photo on POIs with no
 * `image_url`. Reads the real land polygons already on the map (`public/data/land.geojson`),
 * clips to a bounding box roughly covering the empire and its immediate neighbors (Britain to
 * Mesopotamia, the Sahara to the Rhine/Danube), and keeps only every Nth vertex per run of
 * inside-bbox points — the output only needs to read as "a coastline" at ~300x160px, not survive
 * a zoom-in, so aggressive thinning is the right tradeoff against embedding tens of thousands of
 * points in a client bundle.
 *
 * Not true polygon clipping (Sutherland-Hodgman etc.) — a closed ring that crosses the bbox
 * boundary just gets split into open runs of consecutive inside-points, each drawn as its own
 * unclosed subpath. That leaves visible gaps where a landmass exits and re-enters the box, which
 * is fine for a stroked schematic outline (no fill) at thumbnail size.
 *
 * Usage: node scripts/generate-empire-outline.mjs
 * Writes app/empireOutline.ts. Rerun only if `land.geojson` itself changes.
 */
import { readFileSync, writeFileSync } from "node:fs";

const BBOX = { minLng: -11, minLat: 22, maxLng: 48, maxLat: 58 };
const STRIDE = 6; // keep every 6th vertex within an inside-run
const MIN_RUN_POINTS = 4; // drop runs too short to read as a coastline fragment

const land = JSON.parse(readFileSync("public/data/land.geojson", "utf8"));

function inBbox([lng, lat]) {
  return lng >= BBOX.minLng && lng <= BBOX.maxLng && lat >= BBOX.minLat && lat <= BBOX.maxLat;
}

const runs = [];
for (const feature of land.features) {
  const geom = feature.geometry;
  if (!geom) continue;
  const rings = geom.type === "Polygon" ? geom.coordinates : geom.type === "MultiPolygon" ? geom.coordinates.flat() : [];
  for (const ring of rings) {
    let current = [];
    for (const pt of ring) {
      if (inBbox(pt)) {
        current.push(pt);
      } else if (current.length) {
        runs.push(current);
        current = [];
      }
    }
    if (current.length) runs.push(current);
  }
}

const thinned = runs
  .map((run) => run.filter((_, i) => i % STRIDE === 0))
  .filter((run) => run.length >= MIN_RUN_POINTS);

let totalPoints = 0;
const pathParts = thinned.map((run) => {
  totalPoints += run.length;
  return run.map(([lng, lat], i) => `${i === 0 ? "M" : "L"}${lng.toFixed(2)},${(-lat).toFixed(2)}`).join(" ");
});
const d = pathParts.join(" ");

const out = `/** Auto-generated by scripts/generate-empire-outline.mjs — do not hand-edit.
 * A heavily simplified coastline silhouette (Britain to Mesopotamia, Sahara to the
 * Rhine/Danube) used by LocatorThumbnail.tsx [13-P0-3] as a "you are here" locator map for
 * POIs with no image_url. Coordinates are plain [lng, -lat] pairs (SVG y grows downward,
 * latitude grows upward) so the viewBox lines up directly with EMPIRE_BOUNDS below — no
 * runtime projection math needed.
 */
export const EMPIRE_BOUNDS = {
  minLng: ${BBOX.minLng},
  minLat: ${BBOX.minLat},
  maxLng: ${BBOX.maxLng},
  maxLat: ${BBOX.maxLat},
};

export const EMPIRE_OUTLINE_PATH = "${d}";
`;

writeFileSync("app/empireOutline.ts", out);
console.log(`land.geojson -> ${runs.length} runs -> ${thinned.length} kept, ${totalPoints} points, ${(d.length / 1024).toFixed(1)}KB path`);
